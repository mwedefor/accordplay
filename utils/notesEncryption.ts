const RCON = new Uint8Array([0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36]);

// GF(2^8) × table for 2 and 3 (irreducible poly 0x1b)
const MUL2 = new Uint8Array(256);
const MUL3 = new Uint8Array(256);
for (let i = 0; i < 256; i++) {
  const h = i & 0x80;
  const x2 = ((i << 1) & 0xff) ^ (h ? 0x1b : 0);
  MUL2[i] = x2;
  MUL3[i] = x2 ^ i;
}

function _expandKey(key: Uint8Array): Uint8Array {
  const w = new Uint8Array(240);
  w.set(key);
  for (let i = 8; i < 60; i++) {
    const b = (i - 1) * 4;
    let t0 = w[b], t1 = w[b+1], t2 = w[b+2], t3 = w[b+3];
    if (i % 8 === 0) {
      const s = t0;
      t0 = SBOX[t1] ^ RCON[(i >> 3) - 1];
      t1 = SBOX[t2]; t2 = SBOX[t3]; t3 = SBOX[s];
    } else if (i % 8 === 4) {
      t0 = SBOX[t0]; t1 = SBOX[t1]; t2 = SBOX[t2]; t3 = SBOX[t3];
    }
    const o = i * 4, p = (i - 8) * 4;
    w[o] = w[p] ^ t0; w[o+1] = w[p+1] ^ t1;
    w[o+2] = w[p+2] ^ t2; w[o+3] = w[p+3] ^ t3;
  }
  return w;
}

function _shiftRows(s: Uint8Array): void {
  let t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
  t = s[2]; s[2] = s[10]; s[10] = t; t = s[6]; s[6] = s[14]; s[14] = t;
  t = s[3]; s[3] = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = t;
}

function _aesBlock(inp: Uint8Array, rk: Uint8Array): Uint8Array {
  const s = new Uint8Array(inp);
  for (let i = 0; i < 16; i++) s[i] ^= rk[i];
  for (let r = 1; r < 14; r++) {
    for (let i = 0; i < 16; i++) s[i] = SBOX[s[i]];
    _shiftRows(s);
    for (let c = 0; c < 4; c++) {
      const a0 = s[c*4], a1 = s[c*4+1], a2 = s[c*4+2], a3 = s[c*4+3];
      s[c*4]   = MUL2[a0] ^ MUL3[a1] ^ a2      ^ a3;
      s[c*4+1] = a0       ^ MUL2[a1] ^ MUL3[a2] ^ a3;
      s[c*4+2] = a0       ^ a1       ^ MUL2[a2] ^ MUL3[a3];
      s[c*4+3] = MUL3[a0] ^ a1       ^ a2       ^ MUL2[a3];
    }
    const rk0 = r * 16;
    for (let i = 0; i < 16; i++) s[i] ^= rk[rk0 + i];
  }
  for (let i = 0; i < 16; i++) s[i] = SBOX[s[i]];
  _shiftRows(s);
  for (let i = 0; i < 16; i++) s[i] ^= rk[224 + i];
  return s;
}

let _jsRoundKeys: Uint8Array | null = null;

function _decryptJs(encrypted: string): string[] {
  if (!_jsRoundKeys) _jsRoundKeys = _expandKey(_buildKey());
  const data = Uint8Array.from(atob(encrypted), c => c.charCodeAt(0));
  // Layout: iv(12) || ciphertext || auth_tag(16) — strip tag, not verified
  const iv = data.slice(0, 12);
  const ct = data.slice(12, data.length - 16);
  const rk = _jsRoundKeys;

  // GCM counter: J0 = IV || 0x00000001; ciphertext blocks start at J0+1 = IV || 0x00000002
  const ctr = new Uint8Array(16);
  ctr.set(iv);
  ctr[15] = 1; // J0

  const plain = new Uint8Array(ct.length);
  for (let off = 0; off < ct.length; off += 16) {
    // Increment big-endian 32-bit counter at bytes 12-15
    let n = ((ctr[12] << 24) | (ctr[13] << 16) | (ctr[14] << 8) | ctr[15]) >>> 0;
    n = (n + 1) >>> 0;
    ctr[12] = (n >>> 24) & 0xff; ctr[13] = (n >>> 16) & 0xff;
    ctr[14] = (n >>> 8)  & 0xff; ctr[15] =  n         & 0xff;
    const ks = _aesBlock(ctr, rk);
    const len = Math.min(16, ct.length - off);
    for (let j = 0; j < len; j++) plain[off + j] = ct[off + j] ^ ks[j];
  }
  return JSON.parse(new TextDecoder().decode(plain));
}

// ── Public API ────────────────────────────────────────────────────────────────
export async function decryptNotes(encrypted: string): Promise<string[]> {
  if (global.crypto?.subtle) {
    try { return await _decryptSubtle(encrypted); } catch { /* fall through */ }
  }
  return _decryptJs(encrypted);
}
