// AES key fragments — assembled at runtime so no single searchable hex string in bundle
const _m = [0x5e, 0x71, 0x29, 0xb3] as const;
const _g0 = [0xc9,0xd9,0x8b,0xb3,0x2a,0x72,0xfa,0x4a];
const _g1 = [0x5c,0x0c,0xf9,0x94,0xbe,0x36,0x34,0xe3];
const _g2 = [0xd2,0x41,0x5f,0xc1,0x57,0xa5,0x4b,0x3b];
const _g3 = [0x1b,0x81,0xcd,0x8a,0xe1,0xd0,0x67,0x48];

function _buildKey(): Uint8Array {
  return new Uint8Array(
    [_g0, _g1, _g2, _g3].flatMap((g, i) => g.map(b => b ^ _m[i]))
  );
}

// ── crypto.subtle path (when available) ──────────────────────────────────────
let _subtleKey: CryptoKey | null = null;

async function _decryptSubtle(encrypted: string): Promise<string[]> {
  const subtle = global.crypto.subtle;
  if (!_subtleKey) {
    const kb = _buildKey();
    _subtleKey = await subtle.importKey('raw', kb.buffer as ArrayBuffer, { name: 'AES-GCM' }, false, ['decrypt']);
  }
  const data = Uint8Array.from(atob(encrypted), c => c.charCodeAt(0));
  const dec  = await subtle.decrypt({ name: 'AES-GCM', iv: data.slice(0, 12) }, _subtleKey, data.slice(12));
  return JSON.parse(new TextDecoder().decode(dec));
}

